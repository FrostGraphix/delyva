// Generates src/generated/tokens.ts (TS export), dist/tailwind.css (Tailwind v4 theme, light + dark)
// and dist/tailwind-preset.js (Tailwind config preset) from tokens/tokens.json.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { $description: _ignored, ...tokens } = JSON.parse(
  readFileSync(join(root, 'tokens/tokens.json'), 'utf8'),
);

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function writeTs() {
  mkdirSync(join(root, 'src/generated'), { recursive: true });
  const body = `// AUTO-GENERATED by scripts/build.mjs. Do not edit.\n/** Delyva design tokens (see docs/07-design-system.md). */\nexport const tokens = ${JSON.stringify(tokens, null, 2)} as const;\n`;
  writeFileSync(join(root, 'src/generated/tokens.ts'), body);
}

function themeVars(theme) {
  return Object.entries(theme)
    .map(([k, v]) => `  --dl-${kebab(k)}: ${v};`)
    .join('\n');
}

function writeCss() {
  const colors = Object.keys(tokens.theme.light)
    .map((k) => `  --color-${kebab(k)}: var(--dl-${kebab(k)});`)
    .join('\n');
  const lime = Object.entries(tokens.color.lime)
    .map(([k, v]) => `  --color-lime-${k}: ${v};`)
    .join('\n');
  const ink = Object.entries(tokens.color.ink)
    .map(([k, v]) => `  --color-ink-${k}: ${v};`)
    .join('\n');
  const radius = Object.entries(tokens.radius)
    .map(([k, v]) => `  --radius-${k}: ${v}px;`)
    .join('\n');
  const text = Object.entries(tokens.type)
    .map(
      ([k, v]) =>
        `  --text-${kebab(k)}: ${v.size}px;\n  --text-${kebab(k)}--line-height: ${v.line}px;`,
    )
    .join('\n');
  const accentNames = Object.keys(tokens.accent).filter((n) => n !== '$description');
  const accentScale = (name) =>
    Object.entries(tokens.accent[name].scale)
      .map(([k, v]) => `  --dl-accent-${k}: ${v};`)
      .join('\n');
  const accentVars = (name, scheme) => {
    const roles = Object.entries(tokens.accent[name][scheme])
      .map(([k, v]) => `  --dl-${kebab(k)}: ${v};`)
      .join('\n');
    return `${accentScale(name)}\n${roles}`;
  };
  const accentBlocks = accentNames
    .map(
      (n) => `:root[data-accent='${n}'] {
${accentVars(n, 'light')}
}
@media (prefers-color-scheme: dark) {
  :root[data-accent='${n}']:not([data-theme='light']) {
${accentVars(n, 'dark')}
  }
}
:root[data-accent='${n}'][data-theme='dark'] {
${accentVars(n, 'dark')}
}`,
    )
    .join('\n');
  const accentTw = Object.keys(tokens.accent.green.scale)
    .map((k) => `  --color-accent-${k}: var(--dl-accent-${k});`)
    .join('\n');
  const css = `/* AUTO-GENERATED by scripts/build.mjs. Do not edit. */
:root {
${themeVars(tokens.theme.light)}
${accentScale('green')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${themeVars(tokens.theme.dark)}
  }
}
:root[data-theme='dark'] {
${themeVars(tokens.theme.dark)}
}
${accentBlocks}
@theme {
  --spacing: 4px;
  --font-heading: '${tokens.font.family.heading}', ui-sans-serif, system-ui, sans-serif;
  --font-sans: '${tokens.font.family.body}', ui-sans-serif, system-ui, sans-serif;
  --ease-standard: ${tokens.motion.easing.standard};
${colors}
${lime}
${accentTw}
${ink}
${radius}
${text}
}
`;
  writeFileSync(join(root, 'dist/tailwind.css'), css);
}

function writePreset() {
  const colors = Object.fromEntries(
    Object.keys(tokens.theme.light).map((k) => [kebab(k), `var(--dl-${kebab(k)})`]),
  );
  const preset = {
    darkMode: [
      'variant',
      [
        '@media (prefers-color-scheme: dark) { &:not([data-theme=light] *) }',
        '&:is([data-theme=dark] *)',
      ],
    ],
    theme: {
      extend: {
        colors: { ...colors, lime: tokens.color.lime, ink: tokens.color.ink },
        borderRadius: Object.fromEntries(
          Object.entries(tokens.radius).map(([k, v]) => [k, `${v}px`]),
        ),
        spacing: Object.fromEntries(Object.entries(tokens.space).map(([k, v]) => [k, `${v}px`])),
        fontFamily: {
          heading: [tokens.font.family.heading, 'sans-serif'],
          sans: [tokens.font.family.body, 'sans-serif'],
        },
        transitionDuration: Object.fromEntries(
          Object.entries(tokens.motion.duration).map(([k, v]) => [k, `${v}ms`]),
        ),
      },
    },
  };
  writeFileSync(
    join(root, 'dist/tailwind-preset.js'),
    `// AUTO-GENERATED. Tailwind preset (light + dark via CSS variables from tailwind.css).\nexport default ${JSON.stringify(preset, null, 2)};\n`,
  );
  writeFileSync(
    join(root, 'dist/tailwind-preset.d.ts'),
    'declare const preset: Record<string, unknown>;\nexport default preset;\n',
  );
}

mkdirSync(join(root, 'dist'), { recursive: true });
writeTs();
writeCss();
writePreset();
