// Compiles svg/*.svg (24x24 grid, 1.5px stroke, currentColor) into typed React (web) and
// React Native components. Only <path d="..."> elements are supported, by design.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pascal = (s) => s.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

const icons = readdirSync(join(root, 'svg'))
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((file) => {
    const svg = readFileSync(join(root, 'svg', file), 'utf8');
    if (!svg.includes('viewBox="0 0 24 24"')) throw new Error(`${file}: must use a 24x24 viewBox`);
    const paths = [...svg.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((m) => m[1]);
    if (paths.length === 0) throw new Error(`${file}: no <path> elements`);
    return {
      name: file.replace(/\.svg$/, ''),
      component: `${pascal(file.replace(/\.svg$/, ''))}Icon`,
      paths,
    };
  });

const header = '// AUTO-GENERATED by scripts/build.mjs from svg/*.svg. Do not edit.\n';
const data = `${header}/** Path data for every icon, keyed by name. */\nexport const ICON_PATHS = ${JSON.stringify(Object.fromEntries(icons.map((i) => [i.name, i.paths])), null, 2)} as const;\n\n/** Icon name. */\nexport type IconName = keyof typeof ICON_PATHS;\n`;
const comps = (factory, from) =>
  `${header}import { ${factory} } from '${from}';\n\n${icons
    .map(
      (i) =>
        `/** ${i.name} icon (24 grid, 1.5px stroke). */\nexport const ${i.component} = ${factory}('${i.name}');`,
    )
    .join('\n')}\n`;

mkdirSync(join(root, 'src/generated'), { recursive: true });
writeFileSync(join(root, 'src/generated/icon-paths.ts'), data);
writeFileSync(join(root, 'src/generated/web-icons.ts'), comps('createWebIcon', '../web-icon.js'));
writeFileSync(
  join(root, 'src/generated/native-icons.ts'),
  comps('createNativeIcon', '../native-icon.js'),
);
